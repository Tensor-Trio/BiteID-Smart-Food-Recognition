import os
import sys

import numpy as np
import streamlit as st
import tensorflow as tf
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.config import (
    EVAL_DIR,
    IMAGE_SIZE,
    SAMPLE_IMAGES_DIR,
    TRANSFER_MODEL_PATH,
    load_class_names,
)

MODEL_PATH = os.environ.get("BITEID_MODEL_PATH", TRANSFER_MODEL_PATH)
TOP_K = 5
RESPONSIBLE_USE_WARNING = (
    "This system acts strictly as an image classification tool. It is not "
    "validated by domain medical experts and does not make or verify health "
    "or nutritional claims."
)


@st.cache_resource(show_spinner="Loading model...")
def load_model(model_path):
    """Load the trained classifier once per server process."""
    return tf.keras.models.load_model(model_path)


@st.cache_data
def load_names():
    """Load the 101 class labels."""
    return load_class_names()


def preprocess_image(image):
    """Resize to the model input profile and cast to float32.

    Values stay on the raw [0, 255] scale. The trained model owns its own
    input normalization, so the app must not normalize a second time.
    """
    resized = image.convert("RGB").resize((IMAGE_SIZE[1], IMAGE_SIZE[0]))
    array = np.asarray(resized, dtype=np.float32)
    return np.expand_dims(array, axis=0)


def top_predictions(model, image_array, class_names, top_k=TOP_K):
    """Return the ``top_k`` most probable labels with confidences."""
    probabilities = model.predict(image_array, verbose=0)[0]
    order = np.argsort(probabilities)[::-1][:top_k]
    return [
        (class_names[index], float(probabilities[index]))
        for index in order
        if index < len(class_names)
    ]


def render_predictions(model, pil_image, class_names):
    """Display the prediction chart and per-label confidence values."""
    predictions = top_predictions(model, preprocess_image(pil_image), class_names)

    st.subheader("Predictions")
    chart_col, value_col = st.columns([3, 2])

    with chart_col:
        st.bar_chart(
            {label: confidence for label, confidence in predictions},
            horizontal=True,
        )

    with value_col:
        for label, confidence in predictions:
            st.metric(label, f"{confidence:.2%}")

    return predictions


def sample_image_paths():
    """List the bundled demo images."""
    if not os.path.isdir(SAMPLE_IMAGES_DIR):
        return []
    extensions = (".jpg", ".jpeg", ".png")
    return sorted(
        name
        for name in os.listdir(SAMPLE_IMAGES_DIR)
        if name.lower().endswith(extensions)
    )


def known_failure_paths():
    """Return failure images generated by the evaluation pipeline."""
    failure_dir = os.path.join(EVAL_DIR, "failures", "images")
    if not os.path.isdir(failure_dir):
        return []
    extensions = (".jpg", ".jpeg", ".png")
    return sorted(
        os.path.join(failure_dir, name)
        for name in os.listdir(failure_dir)
        if name.lower().endswith(extensions)
    )


def main():
    """Render the dashboard."""
    st.set_page_config(
        page_title="BiteID - Smart Food Recognition",
        page_icon="\U0001f355",
        layout="wide",
    )
    st.title("\U0001f355 BiteID - Smart Food Recognition")
    st.caption("Food-101 image classification using transfer learning")

    if not os.path.exists(MODEL_PATH):
        st.error(
            f"No trained model found at `{MODEL_PATH}`. "
            "Run `python src/train_transfer.py` first."
        )
        st.stop()

    model = load_model(MODEL_PATH)
    class_names = load_names()
    output_count = model.output_shape[-1]
    if output_count != len(class_names):
        st.error(
            "Model/class-label mismatch: "
            f"model outputs {output_count} classes, but class_names.json "
            f"contains {len(class_names)} labels. Retrain or restore the "
            "matching model artifacts."
        )
        st.stop()

    samples = sample_image_paths()
    failures = known_failure_paths()
    st.sidebar.header("Input source")
    mode = st.sidebar.radio(
        "Choose how to provide an image",
        ["Upload an image", "Use a bundled sample", "Known failure case"],
    )

    if mode == "Upload an image":
        uploaded = st.file_uploader(
            "Select a food photo",
            type=["jpg", "jpeg", "png"],
            help="Supported formats: JPG, JPEG, PNG.",
        )
        if uploaded is not None:
            st.image(uploaded, caption="Uploaded image", width=320)
            render_predictions(model, Image.open(uploaded), class_names)
        else:
            st.info("Upload a food photo to see predictions.")
    elif mode == "Use a bundled sample":
        if not samples:
            st.sidebar.warning("No bundled samples found in `app/sample_images/`.")
            st.info("Add Food-101 sample images to populate this view.")
        else:
            selected = st.sidebar.selectbox("Sample image", samples)
            image = Image.open(os.path.join(SAMPLE_IMAGES_DIR, selected))
            st.image(image, caption=selected, width=320)
